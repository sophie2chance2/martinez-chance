// Preserve the original copy and change text only: inputs, selections and handlers stay intact.
let secondaryLanguage = 'es';
try { if (localStorage.getItem('secondaryLanguage') === 'fr') secondaryLanguage = 'fr'; } catch {}
const translatedNodes = new WeakMap();
const translationPairs = [...secondaryTranslations].sort((a, b) => b[0].length - a[0].length);
function languageControl() {
  return `<div class="language-toggle" role="group" aria-label="Translation language">
    <button type="button" data-language="es" lang="es" aria-pressed="${secondaryLanguage === 'es'}">Español</button>
    <button type="button" data-language="fr" lang="fr" aria-pressed="${secondaryLanguage === 'fr'}">Français</button>
  </div>`;
}
function translateSecondaryText(root = document.body) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    const parent = node.parentElement;
    if (!parent || parent.closest('script, style, textarea, [data-language], [data-guest] h4')) continue;
    let record = translatedNodes.get(node);
    if (!record || (node.data !== record.es && node.data !== record.fr)) {
      const original = node.data;
      const trimmed = original.trim();
      const pair = translationPairs.find(([es]) => trimmed === es || trimmed.endsWith(' / ' + es));
      if (!pair) continue;
      const offset = original.lastIndexOf(pair[0]);
      record = { es: original, fr: original.slice(0, offset) + pair[1] + original.slice(offset + pair[0].length), standalone: trimmed === pair[0] };
      translatedNodes.set(node, record);
    }
    const target = record[secondaryLanguage];
    if (node.data !== target) node.data = target;
    if (record.standalone && parent.childNodes.length === 1) parent.lang = secondaryLanguage;
  }
  document.querySelectorAll('[data-language]').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.language === secondaryLanguage)));
}
document.addEventListener('click', event => {
  const button = event.target.closest('[data-language]');
  if (!button) return;
  secondaryLanguage = button.dataset.language;
  try { localStorage.setItem('secondaryLanguage', secondaryLanguage); } catch {}
  translateSecondaryText();
});
// RSVP controls and validation messages are inserted after the initial page render.
new MutationObserver(() => translateSecondaryText()).observe(document.body, { childList: true, subtree: true, characterData: true });
translateSecondaryText();
